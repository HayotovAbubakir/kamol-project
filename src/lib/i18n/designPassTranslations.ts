/** Flatten nested designPass object for translate() dot-path lookup. */
export function flattenDesignPass(obj: Record<string, unknown>, prefix = 'designPass'): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(obj)) {
    const path = `${prefix}.${key}`;
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      Object.assign(out, flattenDesignPass(value as Record<string, unknown>, path));
    } else if (typeof value === 'string') {
      out[path] = value;
    }
  }
  return out;
}
